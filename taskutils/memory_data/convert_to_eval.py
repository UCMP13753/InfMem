import pandas as pd
import json
from pathlib import Path

def convert_parquet_to_json(parquet_file_path: str, json_file_path: str, sample_size: int = None, seed: int = 42):
    """
    Converts a Parquet file generated by the previous script into a JSON file.
    Renames the 'context' column to 'input'.

    Args:
        parquet_file_path (str): The path to the input Parquet file.
        json_file_path (str): The desired path for the output JSON file.
        sample_size (int): Number of random samples to select. If None, use all data.
        seed (int): Random seed for reproducibility.
    """
    # Load the Parquet file into a Pandas DataFrame
    df = pd.read_parquet(parquet_file_path)
    # print(len(df))
    # # Randomly sample if sample_size is specified
    # if sample_size is not None and sample_size < len(df):
    #     df = df.sample(n=sample_size, random_state=seed)
    #     print(f"Randomly selected {sample_size} samples from {len(df)} total records (seed={seed})")

    # # Convert to records
    records = []
    for i, record in enumerate(df.to_dict(orient='records')):
        records.append({
            'context': record['context'],
            'input': record['prompt'][0]['content'],
            'answers': list(record['reward_model']['ground_truth']),
            'num_docs': record['extra_info']['num_docs'],
            'index': record['extra_info']['index'],
        })

    # Save the list of dictionaries to a JSON file
    Path(json_file_path).parent.mkdir(parents=True, exist_ok=True)
    with open(json_file_path, 'w', encoding='utf-8') as f:
        json.dump(records, f, ensure_ascii=False, indent=4)

    print(f"Successfully converted '{parquet_file_path}' to '{json_file_path}'.")
    print(f"Total records saved: {len(records)}")

def merge_json():
    import json, glob, os

    base = "/work/xinyu/MemAgent/hotpotqa"
    files = sorted(glob.glob(os.path.join(base, "sft_training_*.json")))

    merged = []
    for fp in files:
        with open(fp, "r", encoding="utf-8") as f:
            arr = json.load(f)  # each file is a JSON array
            merged.extend(arr)

    # Re-index
    for i, obj in enumerate(merged):
        obj["index"] = i

    out_path = os.path.join("/mnt/nfs/datasets/mem_agent/initial_qa_pairs_for_sft/", "sft_training_merged.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(merged, f, ensure_ascii=False)
    print(f"Done. Wrote {len(merged)} items to {out_path}")


